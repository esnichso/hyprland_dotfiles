def gen_qt_palette(t: Theme) -> str:
    """qt6ct/qt5ct colour scheme: 21 roles per state, #aarrggbb."""

    def row(*keys_or_roles: str) -> str:
        out = []
        for k in keys_or_roles:
            out.append(k if k.startswith("#") else t.argb(k))
        return ", ".join(out)

    active = row(
        "text", "surface0", "surface2", "surface1", "crust", "surface0",
        "text", t.role("urgent").replace("#", "#ff"), "text", "base", "base",
        "crust", t.role("accent").replace("#", "#ff"), "crust",
        t.role("link").replace("#", "#ff"), t.role("accent").replace("#", "#ff"),
        "mantle", "base", "surface0", "text", "overlay0",
    )
    inactive = row(
        "text", "surface0", "surface2", "surface1", "crust", "surface0",
        "text", t.role("urgent").replace("#", "#ff"), "text", "base", "base",
        "crust", "surface2", "text",
        t.role("link").replace("#", "#ff"), t.role("accent").replace("#", "#ff"),
        "mantle", "base", "surface0", "text", "overlay0",
    )
    disabled = row(
        "overlay0", "surface0", "surface2", "surface1", "crust", "surface0",
        "overlay0", t.role("urgent").replace("#", "#ff"), "overlay0", "mantle",
        "base", "crust", "surface1", "overlay0", "overlay0", "overlay0",
        "mantle", "base", "surface0", "overlay0", "surface1",
    )
    return "\n".join([
        "[ColorScheme]",
        f"; {BANNER.format(name=t.stem)}",
        f"; Theme: {t.name}",
        ";",
        "; Role order: WindowText, Button, Light, Midlight, Dark, Mid, Text,",
        "; BrightText, ButtonText, Base, Window, Shadow, Highlight,",
        "; HighlightedText, Link, LinkVisited, AlternateBase, NoRole,",
        "; ToolTipBase, ToolTipText, PlaceholderText",
        "",
        f"active_colors={active}",
        f"inactive_colors={inactive}",
        f"disabled_colors={disabled}",
    ]) + "\n"


