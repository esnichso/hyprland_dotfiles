#!/usr/bin/env python3
"""Render every config's colours from a single palette file.

    ./install/set-theme.py                 list available themes
    ./install/set-theme.py mocha           apply a theme
    ./install/set-theme.py --pick          choose one with rofi
    ./install/set-theme.py mocha --check   verify files are up to date (CI)

Colour used to live in thirteen files as 341 separate hex literals. This
generates all of it from themes/<name>.toml instead, so changing the accent
colour is one edit and one command.

Two mechanisms are used, depending on what each config format supports:

  * a generated file that the real config imports/includes/sources — used
    wherever the format has such a directive (CSS, kitty, rofi, fish,
    hyprlang). The hand-written config stays hand-written.
  * marked regions, replaced in place — used for formats with no import
    (TOML, JSONC). Everything between the >>> and <<< markers is generated;
    everything outside is yours.

Generated files carry a header saying so. Do not edit them; edit the theme.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEMES = ROOT / "themes"
CONFIG = ROOT / "config"

BANNER = "Generated by install/set-theme.py from themes/{name}.toml — do not edit."

REQUIRED_PALETTE = {
    "crust", "mantle", "base", "surface0", "surface1", "surface2",
    "overlay0", "overlay1", "overlay2", "subtext0", "subtext1", "text",
    "rosewater", "flamingo", "pink", "mauve", "red", "maroon", "peach",
    "yellow", "green", "teal", "sky", "sapphire", "blue", "lavender",
}
REQUIRED_ROLES = {"accent", "accent_alt", "urgent", "warning", "success", "info", "link"}
ANSI_ORDER = [
    "black", "red", "green", "yellow", "blue", "magenta", "cyan", "white",
    "bright_black", "bright_red", "bright_green", "bright_yellow",
    "bright_blue", "bright_magenta", "bright_cyan", "bright_white",
]


class Theme:
    def __init__(self, path: Path):
        self.path = path
        self.stem = path.stem
        with path.open("rb") as fh:
            raw = tomllib.load(fh)

        self.name = raw.get("name", self.stem)
        self.dark = raw.get("dark", True)
        self.gtk_theme = raw.get("gtk_theme", "")
        self.icon_theme = raw.get("icon_theme", "Papirus-Dark")
        # Login screen. Not applied by this script — /etc is root-owned and
        # SDDM runs before there is a user session to apply anything to. This
        # only records which theme *would* match; install/sddm.sh reads it and
        # asks for the password once.
        self.sddm_theme = raw.get("sddm_theme", "")
        self.palette: dict[str, str] = raw["palette"]
        self.roles: dict[str, str] = raw["roles"]
        self.ansi: dict[str, str] = raw.get("ansi", {})

        missing = REQUIRED_PALETTE - self.palette.keys()
        if missing:
            sys.exit(f"{path}: [palette] is missing: {', '.join(sorted(missing))}")
        missing = REQUIRED_ROLES - self.roles.keys()
        if missing:
            sys.exit(f"{path}: [roles] is missing: {', '.join(sorted(missing))}")
        for role, key in self.roles.items():
            if key not in self.palette:
                sys.exit(f"{path}: [roles].{role} points at unknown colour '{key}'")
        for slot, key in self.ansi.items():
            if key not in self.palette:
                sys.exit(f"{path}: [ansi].{slot} points at unknown colour '{key}'")
        for key, value in self.palette.items():
            if not (value.startswith("#") and len(value) == 7):
                sys.exit(f"{path}: {key} = {value!r} is not a #rrggbb colour")

    # -- lookups ---------------------------------------------------------

    def hex(self, key: str) -> str:
        """#rrggbb"""
        return self.palette[key]

    def bare(self, key: str) -> str:
        """rrggbb, no hash — kitty, fish and rofi all want this somewhere."""
        return self.palette[key].lstrip("#")

    def role(self, name: str) -> str:
        return self.palette[self.roles[name]]

    def role_bare(self, name: str) -> str:
        return self.role(name).lstrip("#")

    def ansi_hex(self, slot: str) -> str:
        return self.palette[self.ansi.get(slot, "text")]

    def argb(self, key: str, alpha: str = "ff") -> str:
        """#aarrggbb — Qt's palette format."""
        return f"#{alpha}{self.bare(key)}"

    def rgba(self, key: str, alpha: str = "ff") -> str:
        """rgba(rrggbbaa) — Hyprland and hyprlang tools."""
        return f"rgba({self.bare(key)}{alpha})"

    def dec(self, key_or_hex: str) -> str:
        """r,g,b as decimals — KDE's kdeglobals format, which takes nothing else."""
        h = (key_or_hex if key_or_hex.startswith("#") else self.hex(key_or_hex)).lstrip("#")
        return f"{int(h[0:2], 16)},{int(h[2:4], 16)},{int(h[4:6], 16)}"

    def role_dec(self, name: str) -> str:
        return self.dec(self.role(name))


# ---------------------------------------------------------------- writing


DRY_RUN = False  # set by --check; see the note in write()


def write(path: Path, content: str, results: list) -> None:
    """Write, unless --check asked only for a comparison.

    The DRY_RUN guard is not decoration. Without it `--check` wrote every file
    it was supposed to be inspecting, so it reported drift once and silently
    repaired it — meaning `check.sh` passed on the second run no matter what,
    and rendering a theme with --check quietly swapped the live palette.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == content:
        results.append(("same", path))
        return
    if not DRY_RUN:
        path.write_text(content, encoding="utf-8")
    results.append(("wrote", path))


def replace_marked(path: Path, block: str, comment: str, results: list) -> None:
    """Replace the region between >>> and <<< markers, leaving the rest alone."""
    start = f"{comment} >>> palette >>>"
    end = f"{comment} <<< palette <<<"

    text = path.read_text(encoding="utf-8")
    if start not in text or end not in text:
        sys.exit(
            f"{path}: missing palette markers.\n"
            f"  Add these two lines around the colour section:\n"
            f"    {start}\n    {end}"
        )

    head, _, rest = text.partition(start)
    _, _, tail = rest.partition(end)
    new = f"{head}{start}\n{block.rstrip()}\n{end}{tail}"

    if new == text:
        results.append(("same", path))
        return
    if not DRY_RUN:
        path.write_text(new, encoding="utf-8")
    results.append(("wrote", path))


