def apply(t: Theme, check: bool) -> int:
    global DRY_RUN
    DRY_RUN = check
    results: list = []

    write(CONFIG / "hypr/conf/theme.lua", gen_hypr_theme_lua(t), results)
    write(CONFIG / "hypr/colors.conf", gen_hypr_colors_conf(t), results)
    write(CONFIG / "waybar/colors.css", gen_css_colors(t), results)
    write(CONFIG / "swaync/colors.css", gen_css_colors(t), results)
    write(CONFIG / "kitty/colors.conf", gen_kitty_colors(t), results)
    write(CONFIG / "rofi/colors.rasi", gen_rofi_colors(t), results)
    write(CONFIG / "fish/colors.fish", gen_fish_colors(t), results)
    write(CONFIG / "gtk-4.0/gtk.css", gen_gtk4_css(t), results)
    write(CONFIG / "gtk-3.0/gtk.css", gen_gtk3_css(t), results)
    write(CONFIG / "qt6ct/colors/palette.conf", gen_qt_palette(t), results)
    write(CONFIG / "qt5ct/colors/palette.conf", gen_qt_palette(t), results)
    write(CONFIG / "kdeglobals", gen_kdeglobals(t), results)
    write(CONFIG / "hypr/theme.env", gen_theme_env(t), results)
    # A file of its own rather than a marked region: the icon-theme setting
    # lives inside rofi's `configuration { }` block, and a comment inside a
    # rasi block discards every declaration after it — markers included.
    write(CONFIG / "rofi/icons.rasi", gen_rofi_icons(t), results)

    replace_marked(CONFIG / "starship.toml", gen_starship_palette(t), "#", results)
    replace_marked(CONFIG / "waybar/config.jsonc", gen_waybar_calendar(t), "//", results)
    replace_marked(CONFIG / "gtk-3.0/settings.ini", gen_gtk3_theme(t), "#", results)
    replace_marked(CONFIG / "qt6ct/qt6ct.conf", f"icon_theme={t.icon_theme}", ";", results)
    replace_marked(CONFIG / "qt5ct/qt5ct.conf", f"icon_theme={t.icon_theme}", ";", results)

    # Record which theme is live, so scripts and prompts can ask.
    state = Path(os.environ.get("XDG_STATE_HOME", Path.home() / ".local/state")) / "hypr"
    if not check:
        state.mkdir(parents=True, exist_ok=True)
        (state / "theme").write_text(t.stem + "\n", encoding="utf-8")

    changed = [p for status, p in results if status == "wrote"]

    if check:
        if changed:
            print(f"Out of date with themes/{t.stem}.toml:")
            for p in changed:
                print(f"  {p.relative_to(ROOT)}")
            print("\nRun: ./install/set-theme.py " + t.stem)
            return 1
        print(f"All colour files match themes/{t.stem}.toml")
        return 0

    print(f"Applied {t.name} ({t.stem})")
    for status, p in results:
        mark = "\033[32mwrote\033[0m" if status == "wrote" else "unchanged"
        print(f"  {mark:<18} {p.relative_to(ROOT)}")

    if changed:
        print(
            "\nReload the live session with:\n"
            "  hyprctl reload\n"
            "  pkill waybar; waybar & disown\n"
            "  swaync-client -rs\n"
            "  kill -SIGUSR1 $(pgrep kitty)      # kitty re-reads its config\n"
            "  ~/.config/hypr/scripts/theme.sh   # GTK theme name + gsettings\n"
        )
    return 0


def list_themes() -> list[Path]:
    return sorted(THEMES.glob("*.toml"))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("theme", nargs="?", help="theme name (file stem in themes/)")
    ap.add_argument("--pick", action="store_true", help="choose with rofi")
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if any file is out of date")
    args = ap.parse_args()

    available = list_themes()
    if not available:
        sys.exit(f"No themes in {THEMES}")

    name = args.theme

    if args.pick:
        menu = "\n".join(p.stem for p in available)
        try:
            proc = subprocess.run(
                ["rofi", "-dmenu", "-i", "-p", "Theme", "-no-custom",
                 "-theme", "powermenu"],
                input=menu, capture_output=True, text=True, check=False,
            )
        except FileNotFoundError:
            sys.exit("rofi is not installed")
        name = proc.stdout.strip()
        if not name:
            return 0

    if not name:
        print("Available themes:\n")
        current = None
        state = Path(os.environ.get("XDG_STATE_HOME", Path.home() / ".local/state"))
        marker = state / "hypr/theme"
        if marker.exists():
            current = marker.read_text(encoding="utf-8").strip()
        for p in available:
            t = Theme(p)
            flag = "  <- current" if p.stem == current else ""
            print(f"  {p.stem:<12} {t.name}{flag}")
        print("\nApply one:  ./install/set-theme.py <name>")
        return 0

    path = THEMES / f"{name}.toml"
    if not path.exists():
        sys.exit(f"No such theme: {name}\nAvailable: "
                 + ", ".join(p.stem for p in available))

    return apply(Theme(path), args.check)


if __name__ == "__main__":
    sys.exit(main())
